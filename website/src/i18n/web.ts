const webDict: Record<Locale, Record<WebKey, string>> = {
  ru: webRu,
  uk: webUk,
  en: webEn,
};

export function wt(
  locale: Locale,
  key: WebKey,
  params?: Record<string, string | number>,
): string {
  let text = webDict[locale][key] ?? webDict.ru[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}
